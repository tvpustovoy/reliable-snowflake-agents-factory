"""Compile distillation prompt versions into ready-to-run text.

prompt version = role (prompts/roles/<role>.md) + LENS.md §2-6 + BUSINESS_MODEL.md zones + task.
Output (immutable, versioned):
  prompts/compiled/distill_<role>_v<N>.txt   full prompt; runtime placeholders only: {basket} {day} {client_id} {field} {chunk_text}
  prompts/compiled/MANIFEST.md                version, role, sha256, chars, created
  sql/00_prompts.sql                          MERGE into RECPLACE.MODEL.PROMPT_VERSIONS
A new version is written only when the compiled text changes (by sha256).
"""
import datetime, hashlib, json, pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "prompts" / "compiled"
out.mkdir(parents=True, exist_ok=True)
schema = json.loads((root / "prompts" / "schema_v1.json").read_text())

def lens_body():
    text = (root / "LENS.md").read_text()
    parts = re.split(r"^## (\d+)\. (.+)$", text, flags=re.M)
    blocks = []
    for i in range(1, len(parts), 3):
        num, title, body = int(parts[i]), parts[i + 1].strip(), parts[i + 2].strip()
        if 2 <= num <= 6:
            blocks.append(f"{title.upper()}\n{body}")
    return "\n\n".join(blocks)

def zones():
    lines, zone = [], None
    for line in (root / "BUSINESS_MODEL.md").read_text().splitlines():
        m = re.match(r"\|\s*(\*\*(\w+)\*\*)?\s*\|\s*`(\w+)`\s*\|\s*(.+?)\s*\|\s*(.+?)\s*\|$", line)
        if m:
            zone = m.group(2) or zone
            lines.append(f"- {zone}/{m.group(3)}: {m.group(4)}")
    return "\n".join(lines)

TASK = """FIELD (facts other workers already extracted near this chunk; may be empty):
{field}

SOURCE (basket={basket}, date={day}, client_id={client_id}):
<<<
{chunk_text}
>>>

TASK. Respond in JSON matching the schema:
- asserts: 0-6 NEW facts that feed a target query. zone/subzone only from BUSINESS MODEL; claim in Russian, one atomic statement; quote = EXACT verbatim substring of SOURCE, 15-300 characters, never paraphrased, and it alone must fully support the claim; speaker_role founder|sales|client|team|doc|unknown; fact_type promise|risk|problem|decision|rule|price|responsibility|status|need|objection|loss_reason|sales_behavior|training_rule|other; target_q Q1-Q9; knowledge_state known|hypothesis; stake = one line why it matters to the founder; amount_rub, due_date (YYYY-MM-DD), counterparty (role), promise_status open|kept|broken, deal_hint won|lost|stalled|churned|renewed — null when the text does not give them.
- refs: links to FIELD facts this chunk speaks about (fact_id, relation reinforces|contradicts|updates, quote). Reinforce instead of re-asserting.
- signals: 0-3 important open questions (kind gap|question, zone, subzone, text, why_matters).
No phone numbers, emails or personal details in any field. Refer to people by role.

OUTPUT: return ONLY one JSON object, no prose, no code fences, valid against this JSON schema:
"""

def compile_role(role):
    role_text = (root / "prompts" / "roles" / f"{role}.md").read_text().strip()
    return "\n\n".join([role_text, lens_body(), "BUSINESS MODEL (zone/subzone: what to know)\n" + zones(), TASK + json.dumps(schema, ensure_ascii=False)]) + "\n"

manifest = out / "MANIFEST.md"
rows = []
if manifest.exists():
    rows = [l for l in manifest.read_text().splitlines() if l.startswith("| distill_")]
known = {r.split("|")[3].strip(): r for r in rows}  # sha -> row

for role in sorted(p.stem for p in (root / "prompts" / "roles").glob("*.md")):
    text = compile_role(role)
    sha = hashlib.sha256(text.encode()).hexdigest()[:12]
    if sha in known:
        print("unchanged", known[sha].split("|")[1].strip()); continue
    n = 1 + sum(1 for r in rows if f"distill_{role}_v" in r)
    ver = f"distill_{role}_v{n}"
    (out / f"{ver}.txt").write_text(text)
    rows.append(f"| {ver} | {role} | {sha} | {len(text)} | {datetime.date.today()} |")
    known[sha] = rows[-1]
    print("compiled", ver, sha, len(text))

manifest.write_text("# Compiled prompt versions (immutable)\n\n| version | role | sha256[:12] | chars | created |\n|---|---|---|---|---|\n" + "\n".join(rows) + "\n")

q = lambda s: "$$" + s + "$$"
sql = ["-- Generated by prompts/compile.py. Prompt versions are immutable: rows are inserted, never updated.",
       "create table if not exists RECPLACE.MODEL.PROMPT_VERSIONS (version string, role string, sha string, prompt_text string, response_schema variant, created_at timestamp_ltz default current_timestamp());"]
for r in rows:
    ver, role, sha = [c.strip() for c in r.split("|")[1:4]]
    text = (out / f"{ver}.txt").read_text()
    sql.append(f"insert into RECPLACE.MODEL.PROMPT_VERSIONS (version, role, sha, prompt_text, response_schema)\n"
               f"select '{ver}', '{role}', '{sha}', {q(text)}, parse_json({q(json.dumps(schema))})\n"
               f"where not exists (select 1 from RECPLACE.MODEL.PROMPT_VERSIONS where version = '{ver}');")
(root / "sql" / "00_prompts.sql").write_text("\n\n".join(sql) + "\n")
